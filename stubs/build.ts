import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { encodePngIndexed } from '../src/content/formats/png.ts';
import { STUB_SPRITE_FORMAT, STUB_SPRITE_SUFFIX, type StubSpriteManifest } from '../src/content/picture/stub-sprite.ts';
import { DEFAULT_STUBS_DIR } from '../src/node/repo.ts';
import { buildStubAnimationScripts } from './anim-scripts.ts';
import { buildPalette } from './palette.ts';
import { allStubSprites, type StubSprite } from './sprites.ts';
import { buildStubWorld } from './world.ts';

const ATLAS_WIDTH = 256;

function pack(sprite: StubSprite): { width: number; height: number; pixels: Uint8Array; manifest: StubSpriteManifest } {
  const placed: { x: number; y: number }[] = [];
  let x = 0;
  let y = 0;
  let rowH = 0;
  let width = 0;
  for (const f of sprite.frames) {
    const { width: w, height: h } = f.raster;
    if (x > 0 && x + w > ATLAS_WIDTH) {
      x = 0;
      y += rowH + 1;
      rowH = 0;
    }
    placed.push({ x, y });
    x += w + 1;
    rowH = Math.max(rowH, h);
    width = Math.max(width, x - 1);
  }
  const height = y + rowH;
  const pixels = new Uint8Array(width * height);
  sprite.frames.forEach((f, i) => {
    const p = placed[i] ?? { x: 0, y: 0 };
    for (let row = 0; row < f.raster.height; row++) {
      pixels.set(f.raster.pixels.subarray(row * f.raster.width, (row + 1) * f.raster.width), (p.y + row) * width + p.x);
    }
  });
  const name = sprite.path.split('/').at(-1) ?? sprite.path;
  const manifest: StubSpriteManifest = {
    format: STUB_SPRITE_FORMAT,
    image: `${name}.png`,
    frames: sprite.frames.map((f, i) => ({
      x: placed[i]?.x ?? 0,
      y: placed[i]?.y ?? 0,
      w: f.raster.width,
      h: f.raster.height,
      ox: f.ox,
      oy: f.oy,
    })),
    ...(sprite.meta ? { meta: sprite.meta } : {}),
  };
  return { width, height, pixels, manifest };
}

function formatManifest(m: StubSpriteManifest): string {
  const lines = [
    '{',
    `  "format": ${JSON.stringify(m.format)},`,
    `  "image": ${JSON.stringify(m.image)},`,
    '  "frames": [',
    m.frames.map((f) => `    ${JSON.stringify(f)}`).join(',\n'),
    m.meta ? '  ],' : '  ]',
  ];
  if (m.meta) lines.push(`  "meta": ${JSON.stringify(m.meta)}`);
  lines.push('}', '');
  return lines.join('\n');
}

async function writeSprite(dir: string, sprite: StubSprite, palette: Uint8Array): Promise<string> {
  const { width, height, pixels, manifest } = pack(sprite);
  const base = join(dir, sprite.path);
  await mkdir(dirname(base), { recursive: true });
  await writeFile(join(dirname(base), manifest.image), encodePngIndexed(width, height, pixels, palette, { transparentIndex0: true }));
  await writeFile(`${base}${STUB_SPRITE_SUFFIX}`, formatManifest(manifest));
  return `${sprite.path}${STUB_SPRITE_SUFFIX}`;
}

export async function buildStubs(outDir: string): Promise<string[]> {
  const out = resolve(outDir);
  await rm(out, { recursive: true, force: true });
  const palette = buildPalette();
  const written: string[] = [];
  for (const sprite of allStubSprites()) written.push(await writeSprite(out, sprite, palette));
  written.push(...(await buildStubWorld(out, { writeSprite: (dir, sprite) => writeSprite(dir, sprite, palette) })));
  await mkdir(join(out, 'binarydata'), { recursive: true });
  await writeFile(join(out, 'binarydata', 'ja2bin.dat'), await buildStubAnimationScripts());
  written.push('binarydata/ja2bin.dat');
  await writeFile(
    join(out, 'README.txt'),
    'ja2-node stub pack v0. Generated by `pnpm stubs` from stubs/*.ts; original work, not derived from game data.\n',
  );
  return written;
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { out: { type: 'string' } } });
  const out = values.out ?? DEFAULT_STUBS_DIR;
  const files = await buildStubs(out);
  console.log(`stub pack: ${files.length} sprites → ${out}`);
  for (const f of files) console.log(`  ${f}`);
}
